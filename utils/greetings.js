const LAST_TEXT_KEY = 'lastGreetingTextIdx';
const LAST_COLOR_KEY = 'lastGreetingColorIdx';

// 随机抽一条：文案与上一次不同、配色与上一次不同；emoji 取自该配色同色系
function pickGreeting() {
  const tN = GREETINGS.length;
  const cN = COLOR_THEMES.length;

  let tIdx = Math.floor(Math.random() * tN);
  const lastT = wx.getStorageSync(LAST_TEXT_KEY);
  if (lastT === tIdx && tN > 1) {
    tIdx = (tIdx + 1 + Math.floor(Math.random() * (tN - 1))) % tN;
  }

  let cIdx = Math.floor(Math.random() * cN);
  const lastC = wx.getStorageSync(LAST_COLOR_KEY);
  if (lastC === cIdx && cN > 1) {
    cIdx = (cIdx + 1 + Math.floor(Math.random() * (cN - 1))) % cN;
  }

  const theme = COLOR_THEMES[cIdx];
  const emoji = theme.emojis[Math.floor(Math.random() * theme.emojis.length)];

  try {
    wx.setStorageSync(LAST_TEXT_KEY, tIdx);
    wx.setStorageSync(LAST_COLOR_KEY, cIdx);
  } catch (e) { /* ignore */ }

  return { text: GREETINGS[tIdx], color: theme.color, emoji };
}

